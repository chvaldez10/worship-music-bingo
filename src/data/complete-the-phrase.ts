export const PHRASE_CATEGORIES = banks.map(({ id, label }) => ({ id, label }));
export const PHRASE_PROMPTS: PhrasePrompt[] = banks.flatMap(({ id, pairs }) =>
  pairs.map(([first, second, firstCount, note]) => ({
    id: `four-${id}-${first.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${second.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    category: id,
    first,
    second,
    syllables: [firstCount, 4 - firstCount],
    ...(note ? { note } : {}),
  })),
);
// Retain old IDs only to read existing progress; these entries are never drawn.
export const ALL_PHRASE_PROMPTS: PhrasePrompt[] = [
  ...LEGACY_PHRASE_PROMPTS,
  ...RETIRED_FOUR_SYLLABLE_PROMPTS,
  ...PHRASE_PROMPTS,
];
export const phraseKey = (prompt: PhrasePrompt) =>
  `${prompt.first.toLowerCase()}→${prompt.second.toLowerCase()}`;
export function phrasePool() {
  const seen = new Set<string>();
  return PHRASE_PROMPTS.filter((prompt) => {
    const key = phraseKey(prompt);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}
